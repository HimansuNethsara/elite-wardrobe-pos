    private void loadingAnimation() {
        Thread t = new Thread(new Runnable() {
            @Override
            public void run() {
                for (int i = 0; i <= 100; i++) {
                    progressBar.setValue(i); 

                    if (i <= 20) {
                        loadingText.setText("Please wait!");
                    } else if (i <= 30) {
                        loadingText.setText("Loading resources...");
                    } else if (i <= 50) {
                        loadingText.setText("Initializing services...");
                    } else if (i <= 70) {
                        loadingText.setText("Establishing database connection...");
                    } else if (i <= 88) {
                        loadingText.setText("Finalizing UI setup...");
                    } else {
                        loadingText.setText("Done!");
                    }
                    
                    try {
                        if (i <= 20) {
                            Thread.sleep(100); 
                        } else if (i <= 50) {
                            Thread.sleep(50);  
                        } else if (i <= 70) {
                            Thread.sleep(150); 
                        } else {
                            Thread.sleep(30);  
                        }
                    } catch (InterruptedException e) {
                        e.printStackTrace(); 
                    }
                }
            }
        });

        t.start(); // Start the thread to begin animation
    }

    

