    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        try {
                   
        String email = jTextField1.getText();
        String fname = jTextField2.getText();
        String lname = jTextField3.getText();
        String nic = jTextField4.getText();
        String mobile = jTextField5.getText();
        Date birthday = jDateChooser1.getDate();
        String password = String.valueOf(jPasswordField1.getPassword());
        String confirmPassword = String.valueOf(jPasswordField2.getPassword());
        String gender =String.valueOf(jComboBox2.getSelectedItem());
        String type =String.valueOf(jComboBox1.getSelectedItem());
        
        Date date = new Date();
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        
        if (email.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your email", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if(!email.matches("^(?=.{1,64}@)[A-Za-z0-9_-]+(\\.[A-Za-z0-9_-]+)*@[^-][A-Za-z0-9-]+(\\.[A-Za-z0-9-]+)*(\\.[A-Za-z]{2,})$")){
                JOptionPane.showMessageDialog(this, "Invalid email", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (fname.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your first name", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (lname.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your last name", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (nic.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your nic", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (mobile.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your mobile", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (!mobile.matches("^07[01245678]{1}[0-9]{7}$")) {
                JOptionPane.showMessageDialog(this, "Please enter valid mobile number", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (birthday == null) {
                 JOptionPane.showMessageDialog(this, "Please select a valid birthday", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (password.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your password", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (!password.matches("^(?=.*[a-z])(?=.*[A-Z])(?=.*[!@#$%^&*()_+{}\\[\\]:;<>,.?~\\\\/-]).{6,}$")) {
                JOptionPane.showMessageDialog(this, "Please enter minimum eight characters, at least one letter, one number and one special character ", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (!password.equals(confirmPassword)) {
                JOptionPane.showMessageDialog(this, "Passwords do not match", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (gender.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Please select a gender", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (type.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Please select a type", "Warning", JOptionPane.WARNING_MESSAGE);
            }else{
                
               
            ResultSet resultSet = MySQL21.executeSearch("SELECT * FROM `employee` WHERE `email` = '"+email+"' OR `nic` = '"+nic+"' OR `mobile` = '"+mobile+"'");
            if (resultSet.next()) {
                JOptionPane.showMessageDialog(this, "This user is already registered", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {
                
                int rowsAffected = MySQL21.executeIUD("INSERT INTO `employee`(`email`,`password`,`first_name`,`last_name`,`nic`,`mobile`,`date_registered`,`employee_type_id`,`gender_id`) "
                        + "VALUES ('"+email+"', '"+password+"', '"+fname+"', '"+lname+"', '"+nic+"', '"+mobile+"', '"+sdf.format(date)+"', '"+employeeTypeMap.get(type)+"', '"+employeeGenderMap.get(gender)+"')");

                
                if (rowsAffected > 0) {
                    if (selectedImagePath != null && birthday != null) {
                        // Insert into employee_details
                        MySQL21.executeIUD("INSERT INTO `employee_details`(`profile_image`, `birthday`, `employee_email`) " +
                                "VALUES ('" + selectedImagePath + "', '" + sdf.format(birthday) + "', '" + email + "')");
                    }
                    // Refresh employee table in CustomerRegistration
                    if (employeeRegistration != null) {
                        employeeRegistration.loadEmployees(jTextField2.getText());
                    }
                    JOptionPane.showMessageDialog(this, "Employee added successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
                    reset();
                } else {
                    JOptionPane.showMessageDialog(this, "Error adding employee", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
                
                

            }
        
        } catch (Exception e) {
            e.printStackTrace();
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

