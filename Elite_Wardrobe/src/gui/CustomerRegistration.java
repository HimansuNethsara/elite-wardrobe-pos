    private void reset() {
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField5.setText("");
        jTextField1.grabFocus();
        jTextField1.setEditable(true);
        jTable1.clearSelection();
        search();
    }
    
    private void search() {
        
        int sort = jComboBox3.getSelectedIndex();
        
        if (sort == 0) {
            loadCustomers("first_name","ASC",jTextField5.getText());
        }else if(sort == 1){
            loadCustomers("first_name","DESC",jTextField5.getText());
        }else if(sort == 2){
            loadCustomers("points","ASC",jTextField5.getText());
        }else if(sort == 3){
            loadCustomers("points","DESC",jTextField5.getText());
        }
    }
