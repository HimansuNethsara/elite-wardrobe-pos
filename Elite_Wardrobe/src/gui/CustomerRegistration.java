    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        
        int row = jTable1.getSelectedRow();
        
        String mobile = String.valueOf(jTable1.getValueAt(row, 0));
        String fname = String.valueOf(jTable1.getValueAt(row, 1));
        String lname = String.valueOf(jTable1.getValueAt(row, 2));
        String email = String.valueOf(jTable1.getValueAt(row, 3));
        
        jTextField1.setText(email);        
        jTextField2.setText(fname);
        jTextField3.setText(lname);
        
        jTextField5.setText(mobile);
        jTextField5.setEditable(false);
        
        if (evt.getClickCount() == 2) {
            if (orderManagement != null) {
                orderManagement.getjTextField2().setText(String.valueOf(jTable1.getValueAt(row, 0)));
                orderManagement.getjLabe1l6().setText(String.valueOf(jTable1.getValueAt(row, 1)));
                orderManagement.getjTextField4().setText(String.valueOf(jTable1.getValueAt(row, 4)));
                this.dispose();
            }
        }
        
        try {
            
            ResultSet resultSet = MySQL21.executeSearch("SELECT COUNT(id) FROM `invoice` WHERE `customer_mobile` = '"+mobile+"'");
            
            if (resultSet.next()) {
                
                jLabel21.setText(resultSet.getString(1));
                
            }
            
        } catch (Exception e) {
            e.printStackTrace();
        }
        
        //Menu item
        if (evt.getButton() == MouseEvent.BUTTON3 && row >= 0 && row < jTable1.getRowCount()) {
            jPopupMenu1.show(evt.getComponent(), evt.getX(), evt.getY());
        }
        
        
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        String mobile = jTextField1.getText();
        String firstName = jTextField2.getText();
        String lastName = jTextField3.getText();
        String email = jTextField5.getText();
        
            if (firstName.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your first name", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (lastName.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your last name", "Warning", JOptionPane.WARNING_MESSAGE);                        
            }else if (email.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your email", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if(!email.matches("^(?=.{1,64}@)[A-Za-z0-9_-]+(\\.[A-Za-z0-9_-]+)*@[^-][A-Za-z0-9-]+(\\.[A-Za-z0-9-]+)*(\\.[A-Za-z]{2,})$")){
                JOptionPane.showMessageDialog(this, "Invalid email", "Warning", JOptionPane.WARNING_MESSAGE);
            }else{
            
                try {
                    
                    ResultSet resultSet = MySQL21.executeSearch("SELECT * FROM `customer` WHERE `email` = '"+email+"'");
                    
                    boolean canUpdate = false;
                    
                    if (resultSet.next()) {
                                                
                        if (resultSet.getString("mobile").equals(mobile)) {
                            
                            canUpdate = true;
                            
                        }else{
                            JOptionPane.showMessageDialog(this, "Email already added", "Warning", JOptionPane.WARNING_MESSAGE);
                        }
                        
                    }else{
                        canUpdate = true;
                    }
                    
                    if (canUpdate) {
                        
                        MySQL21.executeIUD("UPDATE `customer` SET `first_name`= '"+firstName+"', `last_name`= '"+lastName+"', "
                                + "`email`= '"+email+"' WHERE `mobile` = '"+mobile+"'");
                        
                        JOptionPane.showMessageDialog(this, "Customer updated successfully", "Information", JOptionPane.INFORMATION_MESSAGE);
                        loadCustomers("first_name","ASC",jTextField5.getText());
                        reset();
                        
                    }
                    
                } catch (Exception e) {
                    e.printStackTrace();
                }
                
            }
        
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jMenuItem1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem1ActionPerformed
                      
        int row = jTable1.getSelectedRow();
        if (row != -1) {
            
            String mobile = String.valueOf(jTable1.getValueAt(row, 0));

            
            int response = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this customer?", 
                                                         "Delete Confirmation", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

            if (response == JOptionPane.YES_OPTION) {
                try {
                    
                    MySQL21.executeIUD("DELETE FROM `customer` WHERE `mobile` = '" + mobile + "'");
                    
                    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
                    model.removeRow(row);

                    JOptionPane.showMessageDialog(this, "Customer deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                    reset();

                } catch (Exception e) {
                    logger.log(Level.WARNING,"Error deleting customer!");
                    JOptionPane.showMessageDialog(this, "Please select a customer to delete!", "Warning", JOptionPane.WARNING_MESSAGE);
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Please select a customer to delete!", "Warning", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jMenuItem1ActionPerformed

