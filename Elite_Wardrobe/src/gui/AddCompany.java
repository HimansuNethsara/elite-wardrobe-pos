    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed
        int row= jTable2.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row", "Warning", JOptionPane.WARNING_MESSAGE);
        }else{

            String name = jTextField4.getText();
            String hotline = jTextField6.getText();

            String selectedId = String.valueOf(jTable2.getValueAt(row, 0));
            String selectedName = String.valueOf(jTable2.getValueAt(row, 1));
            String selectedHotline = String.valueOf(jTable2.getValueAt(row, 2));

            if (name.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter company name", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (hotline.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter company hotline", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (!hotline.matches("^(?:0|94|\\+94|0094)?(?:(11|21|23|24|25|26|27|31|32|33|34|35|36|37|38|41|45|47|51|52|54|55|57|63|65|66|67|81|91)(0|2|3|4|5|7|9)|7(0|1|2|4|5|6|7|8)\\d)\\d{6}$")) {
                JOptionPane.showMessageDialog(this, "Please enter valid hotline number", "Warning", JOptionPane.WARNING_MESSAGE);
            }else if (selectedName.equals(name) && selectedHotline.equals(hotline)) {
                JOptionPane.showMessageDialog(this, "Please change name or hotline number to update", "Warning", JOptionPane.WARNING_MESSAGE);
            }else{

                try {

                    ResultSet resultSet = MySQL21.executeSearch("SELECT * FROM `company` WHERE (`name`='"+name+"' OR `hotline` = '"+hotline+"') AND `id` != '"+selectedId+"' ");

                    if (resultSet.next()) {
                        JOptionPane.showMessageDialog(this, "Company name or hotline already used", "Warning", JOptionPane.WARNING_MESSAGE);
                    }else{

                        MySQL21.executeIUD("UPDATE `company` SET `name` = '"+name+"',`hotline` = '"+hotline+"' WHERE `id` = '"+selectedId+"'");
                        loadCompanies();
                        resetCompany();

                    }
                } catch (Exception e) {
                    e.printStackTrace();
                }

            }
        }
    }//GEN-LAST:event_jButton8ActionPerformed

    private void jTable2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable2MouseClicked
        int row = jTable2.getSelectedRow();

        jTextField4.setText(String.valueOf(jTable2.getValueAt(row, 1)));
        jTextField6.setText(String.valueOf(jTable2.getValueAt(row, 2)));

        jButton5.setEnabled(false);

        if (evt.getClickCount() == 2) {

            String name = String.valueOf(jTable2.getValueAt(row, 1));

            supplierManagement.setCompanyName(name);
            this.dispose();
            
            supplierManagement.setCompanyName1(name);
            this.dispose();

            supplierManagement.mobileGrabFocus();
            
            supplierManagement.setCompanyId(String.valueOf(jTable2.getValueAt(row, 0)));

        }

    }//GEN-LAST:event_jTable2MouseClicked

